//! A deliberately small, site-editable drug dictionary.
//!
//! HOSxP's `drugitems.name` is a local label, not a national product code.
//! The dictionary maps common generic names and Thai transliterations to a
//! stable `key` plus therapeutic `classes`, so interaction rules can be
//! written once and reviewed by a pharmacist. When a drug is not resolved,
//! the UI says so and the coverage report marks the affected checks as
//! partial - the engine never pretends an unknown drug is safe.

use serde::{Deserialize, Serialize};

/// One generic drug profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DrugProfile {
    /// Stable key used by rules.
    pub key: &'static str,
    /// Thai generic label.
    pub name_th: &'static str,
    /// English generic label.
    pub name_en: &'static str,
    /// Lowercase matching aliases (English and Thai).
    pub aliases: &'static [&'static str],
    /// Therapeutic classes used by rules.
    pub classes: &'static [&'static str],
    /// Whether the drug is on the high-alert list.
    pub high_alert: bool,
}

/// Result of resolving one HOSxP drug name.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct DrugResolution {
    /// Generic key, when resolved.
    pub key: Option<String>,
    /// Thai or English generic label.
    pub display_name: Option<String>,
    /// Classes of the resolved generic.
    pub classes: Vec<String>,
    /// High-alert flag.
    pub high_alert: bool,
    /// Whether the name matched a profile.
    pub known: bool,
    /// The alias that matched, for the settings/debug surface.
    pub matched_alias: Option<String>,
}

/// Resolve one HOSxP drug name (e.g. "Warfarin 3 mg").
///
/// The longest matching alias wins, so "enoxaparin" resolves before
/// "heparin" and "co-trimoxazole" before "trimethoprim".
pub fn resolve_drug(name: &str) -> DrugResolution {
    let normalized = normalize(name);
    let mut best: Option<(usize, &DrugProfile, &'static str)> = None;
    if !normalized.is_empty() {
        for profile in PROFILES {
            for alias in profile.aliases {
                let alias_normalized = normalize(alias);
                if alias_normalized.len() < 3 {
                    continue;
                }
                if normalized.contains(&alias_normalized) {
                    let score = alias_normalized.len();
                    if best.as_ref().is_none_or(|(current, _, _)| score > *current) {
                        best = Some((score, profile, alias));
                    }
                }
            }
        }
    }
    match best {
        Some((_, profile, alias)) => DrugResolution {
            key: Some(profile.key.to_string()),
            display_name: Some(display_name(profile)),
            classes: profile.classes.iter().map(|s| s.to_string()).collect(),
            high_alert: profile.high_alert,
            known: true,
            matched_alias: Some(alias.to_string()),
        },
        None => DrugResolution {
            key: None,
            display_name: None,
            classes: Vec::new(),
            high_alert: false,
            known: false,
            matched_alias: None,
        },
    }
}

fn display_name(profile: &DrugProfile) -> String {
    if profile.name_th.is_empty() {
        profile.name_en.to_string()
    } else {
        profile.name_th.to_string()
    }
}

/// All profiles, for documentation and future dictionary settings.
pub fn all_profiles() -> &'static [DrugProfile] {
    PROFILES
}

/// Thai label for a therapeutic class key.
pub fn class_label(key: &str) -> &'static str {
    for (class_key, label) in CLASS_LABELS {
        if *class_key == key {
            return label;
        }
    }
    "กลุ่มยาอื่น"
}

fn normalize(text: &str) -> String {
    text.chars()
        .flat_map(|c| c.to_lowercase())
        .filter(|c| c.is_alphanumeric())
        .collect()
}

