const fn profile(
    key: &'static str,
    name_th: &'static str,
    name_en: &'static str,
    aliases: &'static [&'static str],
    classes: &'static [&'static str],
    high_alert: bool,
) -> DrugProfile {
    DrugProfile {
        key,
        name_th,
        name_en,
        aliases,
        classes,
        high_alert,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn resolves_common_names_and_strengths() {
        let r = resolve_drug("Warfarin 3 mg");
        assert_eq!(r.key.as_deref(), Some("warfarin"));
        assert!(r.classes.contains(&"anticoagulant".to_string()));
        assert!(r.high_alert);

        let r = resolve_drug("ไอบูโพรเฟน 400 mg");
        assert_eq!(r.key.as_deref(), Some("ibuprofen"));
        assert!(r.classes.contains(&"nsaid".to_string()));
    }

    #[test]
    fn enoxaparin_wins_over_heparin() {
        let r = resolve_drug("Enoxaparin 40 mg/0.4 mL");
        assert_eq!(r.key.as_deref(), Some("enoxaparin"));
    }

    #[test]
    fn cotrimoxazole_wins_over_trimethoprim_alias() {
        let r = resolve_drug("Co-trimoxazole 480 mg");
        assert_eq!(r.key.as_deref(), Some("co_trimoxazole"));
    }

    #[test]
    fn unknown_drug_is_reported_as_unknown() {
        let r = resolve_drug("Some Unlisted Herbal Product");
        assert!(!r.known);
        assert!(r.key.is_none());
    }

    #[test]
    fn class_labels_are_available() {
        assert_eq!(class_label("nsaid"), "ยากลุ่ม NSAIDs");
        assert_eq!(class_label("unknown_class"), "กลุ่มยาอื่น");
    }
}
